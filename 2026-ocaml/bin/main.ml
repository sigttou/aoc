(* CLI runner: dune exec bin/main.exe [today|N|scaffold N|fetch N] [--example] [--bench]
 *)

(* --- 1. Days & ANSI ---------------------------------------------------------- *)

(* [Index.days] is generated by the rule in lib/dune: every lib/dayNN.ml
   exposes (module DayNN : Util.S) = part1/part2 taking the raw input. *)
let days = Index.days

let latest () = List.fold_left (fun acc (d, _) -> max acc d) 0 days

let bold s = "\027[1m" ^ s ^ "\027[0m"
let italic s = "\027[3m" ^ s ^ "\027[0m"
let green s = "\027[32m" ^ s ^ "\027[0m"

(* --- 2. Timing --------------------------------------------------------------- *)

(* Repeated runs until [min_samples] ran and [target] seconds of wall time
   passed (mirrors the 2024 rust template: ~0.5s, capped at 10000 runs). *)
let benchf ~(f : unit -> string) ~(min_samples : int) : float * int =
  let target = 0.5 in
  let rec loop n acc =
    if n >= 10000 || (n >= min_samples && acc >= target) then
      (acc /. float_of_int n, n)
    else
      let t0 = Unix.gettimeofday () in
      ignore (f ());
      loop (n + 1) (acc +. (Unix.gettimeofday () -. t0))
  in
  loop 0 0.

let fmt_duration secs =
  let us = secs *. 1e6 in
  if us < 1000. then Printf.sprintf "%.3fµs" us
  else if us < 1000_000. then Printf.sprintf "%.3fms" (us /. 1e3)
  else Printf.sprintf "%.3fs" (us /. 1e6)

let run_part label f input bench =
  let t0 = Unix.gettimeofday () in
  let result = f input in
  let single = Unix.gettimeofday () -. t0 in
  let timing =
    if bench && single < 0.5 then
      let avg, n = benchf ~f:(fun () -> f input) ~min_samples:10 in
      Printf.sprintf "%s (%d samples)" (fmt_duration avg) n
    else fmt_duration single
  in
  Printf.printf "  %s:%s %s\n" label
    (green (Printf.sprintf "%-24s" (String.trim result)))
    (italic timing)

(* --- 3. Running solutions ----------------------------------------------------- *)

let input_for example day =
  if example then Util.example_path day else Util.input_path day

(* Runs every registered day on its real (or example) input. Days missing
   their input file are reported, not skipped silently. *)
let run ~(example : bool) ~(bench : bool) ~(only : int list) =
  List.iter
    (fun (day, sol) ->
      if List.mem day only || only = [] then
        let (module M : Util.S) = sol in
        let path = input_for example day in
        if Sys.file_exists path then (
          let input = In_channel.with_open_bin path In_channel.input_all in
          Printf.printf "%s\n" (bold (Printf.sprintf "Day %02d%s" day
                                      (if example then " (example)" else "")));
          run_part "part1" M.part1 input bench;
          run_part "part2" M.part2 input bench)
        else
          Printf.printf "%s no input at %s\n" (bold (Printf.sprintf "Day %02d" day)) path)
    days

(* --- 4. Fetching -------------------------------------------------------------- *)

(* Personal puzzle inputs, session cookie from ~/.config/aoc/session.cookie
   (or $AOC_COOKIE_FILE) creates data/inputs/NN.txt.
   Existing files are not overwritten
 *)
let year = 2026

let cookie_file () =
  match Sys.getenv_opt "AOC_COOKIE_FILE" with
  | Some f -> f
  | None -> Filename.concat (Sys.getenv "HOME") ".config/aoc/session.cookie"

let fetch_input (day : int) : bool =
  let dest = Util.input_path day in
  if Sys.file_exists dest then
    (Printf.printf "  %s already exists, skipping fetch\n" dest; true)
  else (
    let cf = cookie_file () in
    if not (Sys.file_exists cf) then (
      Printf.eprintf "  no session cookie found at %s — not fetching\n" cf;
      Printf.eprintf "  paste your input into %s manually\n" dest;
      false)
    else
      let cmd =
        Printf.sprintf
          {|
set -e; s="$(cat '%s')"; curl -sf --compressed \
  -H "Cookie: session=$s" -H "user-agent: aoc-2026-ocaml" \
  "https://adventofcode.com/%d/day/%d/input" -o '%s'
|}
          cf year day dest
      in
      if Sys.command cmd = 0 then
        (Printf.printf "  input for day %d saved to %s\n" day dest; true)
      else (
        if Sys.file_exists dest then Sys.remove dest;
        Printf.eprintf "  fetch failed (wrong cookie or puzzle not released yet?)\n";
        false))

(* --- 5. Scaffolding ------------------------------------------------------------ *)

(* Skeleton: any new lib/dayNN.ml exposing part1/part2 : string -> string is
   picked up automatically (see README, Template format). *)
let day_template (day : int) : string =
  Printf.sprintf
    {|
(* --- Day %d: <Puzzle Title> ---
 * https://adventofcode.com/2026/day/%d
 *)

type model = { lines : string list }

let parse (input : string) : model =
  { lines = input |> String.split_on_char '\n'
                   |> List.filter_map (fun l -> if l = "" then None else Some l) }

let part1 (input : string) : string =
  let { lines } = parse input in
  Printf.sprintf "%%d" (List.length lines)

let part2 (input : string) : string =
  let { lines } = parse input in
  Printf.sprintf "%%d" (List.length lines)
|}
    day day

let run_scaffold (day : int) =
  let path = Printf.sprintf "lib/day%02d.ml" day in
  if Sys.file_exists path then Printf.printf "%s already exists, not overwriting.\n" path
  else
    let out = open_out path in
    output_string out (day_template day);
    close_out out;
    Printf.printf "created %s\n" path;
    flush stdout;
    ignore (fetch_input day)

(* --- 6. CLI -------------------------------------------------------------------- *)

let () =
  let args = Array.to_list Sys.argv in
  let example = List.mem "--example" args in
  let bench = List.mem "--bench" args in
  let positional =
    args |> List.filter (fun a -> String.length a > 0 && a.[0] <> '-' && a <> Sys.argv.(0)) in
  match positional with
  | [ "scaffold"; n ] -> run_scaffold (int_of_string n)
  | [ "fetch"; n ] -> ignore (fetch_input (int_of_string n))
  | [ "today" ] -> run ~example ~bench ~only:[ latest () ]
  | [ day ] -> run ~example ~bench ~only:[ int_of_string day ]
  | [] -> run ~example ~bench ~only:[]
  | other ->
      Printf.eprintf "unknown arguments: %s\n" (String.concat " " other);
      Printf.eprintf "usage: main.exe [today|N|scaffold N|fetch N] [--example] [--bench]\n";
      exit 2
